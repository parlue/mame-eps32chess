"""Create the small local ESP Lua payload from the installed CB-Emu plugin.

No ROMs, executable files or Windows configuration are copied.
"""
from pathlib import Path
import argparse,hashlib,json,re
p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);a=p.parse_args()
root=Path(__file__).resolve().parents[1];src=a.source/'MessChess/plugins/chessengine'
original=(src/'init.lua').read_text(encoding='utf-8-sig')
s=original
s=re.sub(r'local scr = \[\[.*?\]\]', '',s,count=1,flags=re.S)
s=s.replace('local rand_delay = 1','local rand_delay = 0') # reproducible embedded startup
start=s.index('local function recv_cmd()');end=s.index('local function send_cmd(cmd)',start)
s=s[:start]+'local function recv_cmd() return host.receive() end\n\n'+s[end:]
s=s.replace('io.stdout:write(cmd .. "\\n")\n\tio.stdout:flush()','host.emit(cmd)')
s=s.replace('conth:continue(conth.result)','-- Queue input is non-blocking; there is no stdin thread.')
s=s.replace('loadfile(plugin_path .. "/interfaces/" .. name .. ".lua", "t", env)', '(function() local source = host.interface_source(name); if source then return assert(load(source, name, "t", env)) end end)()')
# UCI button commands have no value. Invalid Speed must never change timing.
s=s.replace('if (string.lower(name) == "speed") then','if (string.lower(name) == "speed") then\n\t\tif not tonumber(value) or tonumber(value)<0 or tonumber(value)>10000 then return end')
s=s.replace("local opt_name, opt_val = string.match(cmd:sub(16), '(.+) value (.+)')", "local opt_name, opt_val = string.match(cmd:sub(16), '(.+) value (.+)')\n\t\tif not opt_name then opt_name=cmd:sub(16); opt_val='' end")
s=s.replace('local function execute_uci_command(cmd)','local function execute_uci_command(cmd)\n\tif cmd == "position startpos" then return end\n\tif cmd:match("^position fen ") then error("FEN setup is not enabled in the first ESP port") end')
# Keep the protocol's move translation and special-move handling unchanged.
s=s[:s.index('function exports.startplugin()')]
start_machine='''
local system = manager:machine():system().name
module = system
interface = load_interface(system)
if not interface then interface = load_interface(manager:machine():system().parent) end
assert(interface, "missing interface for " .. system)
local deadline, co = 0, nil
return { poll = function(now)
    if now < deadline then return end
    if not co or coroutine.status(co)=="dead" then co=coroutine.create(update) end
    host.budget(co)
    local ok, wait = coroutine.resume(co)
    if not ok then error(wait) end
    deadline = now + (tonumber(wait) or 0.01)
end }
end
'''
s='''-- Adapted locally from Sandro Ronco & Franz Huber's chessengine (BSD-3-Clause).
-- Cooperative ESP runtime: no stdin/stdout, threads, lfs or MAME Lua frontend.
return function(host)
local manager = host.manager
local emu = setmetatable({wait=function(seconds) coroutine.yield(seconds) end}, {__index=host.emu})
'''+s+start_machine
payload={'bridge':s,'bootstrap':(root/'lua/bootstrap.lua').read_text(encoding='utf-8')}
for name in ['mm4','mm5']:payload[name]=(src/f'interfaces/{name}.lua').read_text(encoding='utf-8-sig')
dest=root/'generated';dest.mkdir(exist_ok=True)
header='// Generated by tools/import_cbemu.py from the local installation.\n'
for name,code in payload.items():
    (dest/f'{name}.lua').write_text(code,encoding='utf-8')
    chunks=[code[i:i+3000] for i in range(0,len(code),3000)]
    header+=f'static constexpr char payload_{name}[] =\n'+ '\n'.join(f'R"cbemu_payload({c})cbemu_payload"' for c in chunks)+';\n'
(dest/'payload.h').write_text(header,encoding='utf-8')
manifest={'origin':str(src),'upstream_author':'Sandro Ronco & Franz Huber','upstream_license':'BSD-3-Clause (init.lua metadata)','original_init_sha256':hashlib.sha256(original.encode()).hexdigest(),'payload':{n:{'bytes':len(c.encode()),'sha256':hashlib.sha256(c.encode()).hexdigest()} for n,c in payload.items()}}
(dest/'manifest.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
print('Generated local MM IV / MM V payload:',sum(len(c.encode()) for c in payload.values()),'bytes')
